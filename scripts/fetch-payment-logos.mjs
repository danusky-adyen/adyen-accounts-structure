/** Strips everything a renderer does not need, and normalises quoting. */
function tidy(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!DOCTYPE[^>]*>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(title|desc|metadata)\b[\s\S]*?<\/\1>/g, '')
    .replace(/\s+xmlns:xlink="[^"]*"/g, (match) => match)
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

function viewBoxOf(svg, id) {
  const explicit = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (explicit) return explicit.trim();
  const width = /\swidth="(\d+(?:\.\d+)?)"/.exec(svg)?.[1];
  const height = /\sheight="(\d+(?:\.\d+)?)"/.exec(svg)?.[1];
  if (width && height) return `0 0 ${width} ${height}`;
  throw new Error(`${id}: no viewBox and no width/height`);
}

const entries = [];
for (const [id, label, group] of METHODS) {
  const response = await fetch(`${CDN}/${id}.svg`);
  if (!response.ok) throw new Error(`${id}: HTTP ${response.status}`);
  const svg = tidy(await response.text());
  if (!svg.startsWith('<svg')) throw new Error(`${id}: not an SVG`);
  entries.push({ id, label, group, viewBox: viewBoxOf(svg, id), svg });
  process.stdout.write(`${id} ${svg.length}\n`);
}

const total = entries.reduce((sum, entry) => sum + entry.svg.length, 0);

const file = `/**
 * Payment-method brand marks, vendored from Adyen's public logo CDN
 * (${CDN}/<id>.svg).
 *
 * Generated by scripts/fetch-payment-logos.mjs — do not edit by hand.
 * ${entries.length} logos, ${total} bytes of markup.
 *
 * This module is imported lazily: a diagram without payment methods never
 * downloads it.
 */

export interface PaymentLogo {
  readonly viewBox: string;
  /** Complete SVG document, inlined as a data URL by callers. */
  readonly svg: string;
}

export const PAYMENT_LOGOS: Record<string, PaymentLogo> = {
${entries
  .map((entry) => `  ${entry.id}: {\n    viewBox: '${entry.viewBox}',\n    svg: ${JSON.stringify(entry.svg)},\n  },`)
  .join('\n')}
};
`;

await writeFile(new URL('../src/design/paymentLogos.ts', import.meta.url), file, 'utf8');

